def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def run_psql(dburl: str, sql: str) -> str:
    result = subprocess.run(
        ["psql", dburl, "-At", "-v", "ON_ERROR_STOP=1", "-c", sql],
        text=True,
        capture_output=True,
        check=True,
    )
    return result.stdout


def build_markdown(name: str, spec: dict) -> str:
    must = "\n".join(f"- {item}" for item in spec["must"])
    deliverable = "\n".join(f"- {item}" for item in spec["deliverable"])
    return f"""# {name}

你是 Finance Anything 万能决策助手团队的 **{spec["title"]}**。

## 核心使命
{spec["mission"]}

## 你必须做到
{must}

## 标准交付
{deliverable}

## 本角色的数据能力
{spec["akshare"]}

{COMMON}
"""


def main() -> None:
    dburl = os.environ["FINANCE_DB_URL"]
    names = ",".join(q(name) for name in AGENTS)

    for name, spec in AGENTS.items():
        sql = (
            "update agents set "
            f"title={q(spec['title'])}, "
            f"capabilities={q(spec['capabilities'])}, "
            "updated_at=now() "
            f"where name={q(name)};"
        )
        run_psql(dburl, sql)

    rows = run_psql(
        dburl,
        "select name || E'\\t' || id || E'\\t' || coalesce(adapter_config->>'instructionsRootPath','') "
        f"from agents where name in ({names}) order by company_id, name;",
    ).splitlines()

    updated_files = 0
    for row in rows:
        name, _agent_id, root = row.split("\t")
        if not root:
            continue
        root_path = Path(root)
        root_path.mkdir(parents=True, exist_ok=True)
        (root_path / "AGENTS.md").write_text(build_markdown(name, AGENTS[name]), encoding="utf-8")
        updated_files += 1

    print(f"updated_agents={len(rows)} updated_instruction_files={updated_files}")


if __name__ == "__main__":
    main()
